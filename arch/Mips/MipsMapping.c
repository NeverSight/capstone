void Mips_reg_access(const cs_insn *insn, cs_regs regs_read,
		     uint8_t *regs_read_count, cs_regs regs_write,
		     uint8_t *regs_write_count)
{
	uint8_t i;
	uint8_t read_count, write_count;
	cs_mips *mips = &(insn->detail->mips);

	read_count = insn->detail->regs_read_count;
	write_count = insn->detail->regs_write_count;

	// implicit registers
	memcpy(regs_read, insn->detail->regs_read,
	       read_count * sizeof(insn->detail->regs_read[0]));
	memcpy(regs_write, insn->detail->regs_write,
	       write_count * sizeof(insn->detail->regs_write[0]));

	// explicit registers
	for (i = 0; i < mips->op_count; i++) {
		cs_mips_op *op = &(mips->operands[i]);
		switch ((int)op->type) {
		case MIPS_OP_REG:
			if ((op->access & CS_AC_READ) &&
			    !arr_exist_inline(regs_read, read_count, op->reg)) {
				regs_read[read_count] = (uint16_t)op->reg;
				read_count++;
			}
			if ((op->access & CS_AC_WRITE) &&
			    !arr_exist_inline(regs_write, write_count,
					      op->reg)) {
				regs_write[write_count] = (uint16_t)op->reg;
				write_count++;
			}
			break;
		case MIPS_OP_MEM:
			// registers appeared in memory references always being read
			if ((op->mem.base != MIPS_REG_INVALID) &&
			    !arr_exist_inline(regs_read, read_count,
					      op->mem.base)) {
				regs_read[read_count] = (uint16_t)op->mem.base;
				read_count++;
			}
			if ((insn->detail->writeback) &&
			    (op->mem.base != MIPS_REG_INVALID) &&
			    !arr_exist_inline(regs_write, write_count,
					      op->mem.base)) {
				regs_write[write_count] =
					(uint16_t)op->mem.base;
				write_count++;
			}
		default:
			break;
		}
	}

	*regs_read_count = read_count;
	*regs_write_count = write_count;
}

static unsigned Mips_frame_id(const MCInst *MI)
{
	switch (MCInst_getOpcode(MI)) {
	case Mips_Save16:
	case Mips_SaveX16:
		return MIPS_INS_SAVE;
	case Mips_Restore16:
	case Mips_RestoreX16:
		return MIPS_INS_RESTORE;
	default:
		return MIPS_INS_INVALID;
	}
}

void Mips_set_instr_map_data(MCInst *MI)
{
	unsigned frame_id = Mips_frame_id(MI);
	if (frame_id) {
		MI->flat_insn->id = frame_id;
		if (!detail_is_set(MI))
			return;
		cs_mips *m = &get_detail(MI)->mips;
		m->op_count = MCInst_getNumOperands(MI);
		for (unsigned n = 0; n < m->op_count; ++n) {
			MCOperand *op = MCInst_getOperand(MI, n);
			cs_mips_op *out = &m->operands[n];
			if (MCOperand_isReg(op)) {
				out->type = MIPS_OP_REG;
				out->reg = MCOperand_getReg(op);
				out->is_reglist = true;
#ifndef CAPSTONE_DIET
				out->access = frame_id == MIPS_INS_SAVE ?
						      CS_AC_READ :
						      CS_AC_WRITE;
#endif
			} else {
				out->type = MIPS_OP_IMM;
				out->imm = MCOperand_getImm(op);
			}
		}
#ifndef CAPSTONE_DIET
		map_add_implicit_read(MI, MIPS_REG_SP);
		map_add_implicit_write(MI, MIPS_REG_SP);
		add_group(MI, MIPS_FEATURE_INMIPS16MODE);
#endif
		return;
	}
	// Fixes for missing groups.
	if (MCInst_getOpcode(MI) == Mips_JR) {
		unsigned Reg = MCInst_getOpVal(MI, 0);
		switch (Reg) {
		case MIPS_REG_RA:
		case MIPS_REG_RA_64:
			add_group(MI, MIPS_GRP_RET);
			break;
		}
	}

	map_cs_id(MI, mips_insns, ARR_SIZE(mips_insns));
	map_implicit_reads(MI, mips_insns);
	map_implicit_writes(MI, mips_insns);
	map_groups(MI, mips_insns);
#ifndef CAPSTONE_DIET
	if ((MI->csh->mode & CS_MODE_MIPS16) && detail_is_set(MI)) {
		cs_detail *detail = get_detail(MI);
		for (unsigned i = 0; i < detail->groups_count; ++i)
			if (detail->groups[i] == MIPS_FEATURE_HASSTDENC)
				detail->groups[i] = MIPS_FEATURE_INMIPS16MODE;
	}
	switch (MCInst_getOpcode(MI)) {
	case Mips_Bteqz16:
	case Mips_Btnez16:
	case Mips_BteqzX16:
	case Mips_BtnezX16:
		add_group(MI, MIPS_GRP_BRANCH_RELATIVE);
		break;
	default:
		break;
	}
#endif
}

bool Mips_getInstruction(csh handle, const uint8_t *code, size_t code_len,
			 MCInst *instr, uint16_t *size, uint64_t address,
			 void *info)
{
	uint64_t size64;
	Mips_init_cs_detail(instr);
/* The dedicated scan shortens the ordinary table walk on Linux AArch64
 * hosts without adding work to the time-critical formatted path on x64. */
#if defined(CAPSTONE_MIPS_ONLY) && defined(__linux__) && defined(__aarch64__) && \
    defined(__GNUC__)
	const cs_mode mode = instr->csh->mode & ~CS_MODE_BIG_ENDIAN;
	if (code_len >= 4 && instr->csh->no_text && !instr->flat_insn->detail &&
	    instr->csh->disasm == Mips_getInstruction &&
	    (mode == CS_MODE_MIPS32 || mode == CS_MODE_MIPS64)) {
		/* For these standard immediate and load/store encodings all
		 * register and immediate bits are operands. */
		const unsigned major = readBytes32(instr, code) >> 26;
		unsigned opcode = 0;
		switch (major) {
		case 9:
			opcode = Mips_ADDiu;
			break;
		case 12:
			opcode = Mips_ANDi;
			break;
		case 13:
			opcode = Mips_ORi;
			break;
		case 14:
			opcode = Mips_XORi;
			break;
		case 25:
			if (mode == CS_MODE_MIPS64)
				opcode = Mips_DADDiu;
			break;
		case 35:
			opcode = Mips_LW;
			break;
		case 43:
			opcode = Mips_SW;
			break;
		case 55:
			if (mode == CS_MODE_MIPS64)
				opcode = Mips_LD;
			break;
		case 63:
			if (mode == CS_MODE_MIPS64)
				opcode = Mips_SD;
			break;
		}
		if (opcode) {
			MCInst_setOpcode(instr, opcode);
			map_cs_id(instr, mips_insns, ARR_SIZE(mips_insns));
			*size = 4;
			return true;
		}
	}
#endif
	instr->MRI = (MCRegisterInfo *)info;
	map_set_fill_detail_ops(instr, true);

	DecodeStatus Result = Mips_LLVM_getInstruction(instr, &size64, code,
						       code_len, address, info);
	*size = size64;
	if (Result != MCDisassembler_Fail) {
		Mips_set_instr_map_data(instr);
	}
	if (Result == MCDisassembler_SoftFail) {
		MCInst_setSoftFail(instr);
	}
	return Result != MCDisassembler_Fail;
}

