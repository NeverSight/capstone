unsigned Mips_getRegisterListCount(const MCInst *MI)
{
	switch (MCInst_getOpcode(MI)) {
	case Mips_SWM32_MM:
	case Mips_LWM32_MM:
	case Mips_SWM16_MM:
	case Mips_SWM16_MMR6:
	case Mips_LWM16_MM:
	case Mips_LWM16_MMR6:
		return MCInst_getNumOperands(MI) - 2;
	default:
		return 0;
	}
}

