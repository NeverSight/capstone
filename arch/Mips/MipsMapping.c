void Mips_printer(MCInst *MI, SStream *O, void * /* MCRegisterInfo* */ info)
{
	MCRegisterInfo *MRI = (MCRegisterInfo *)info;
	MI->MRI = MRI;
	const char *tmove = NULL;
	if ((MI->csh->mode & CS_MODE_MIPS16) &&
	    MCInst_getNumOperands(MI) == 4 &&
	    MCInst_getOpVal(MI, 2) == MIPS_REG_T8) {
		switch (MCInst_getOpcode(MI)) {
#define M16E2_TMOVE(Opcode, Text) \
	case Mips_##Opcode: \
		tmove = Text; \
		break;
#include "Mips16E2Encodings.inc"
#undef M16E2_TMOVE
		default:
			break;
		}
	}
	if (tmove) {
		// A physical MIPS16e2 spelling with canonical MOVZ/MOVN semantics,
		// not a Capstone alias ID or a different alias operand layout.
		SStream_concat0(O, tmove);
		for (unsigned n = 0; n < 2; ++n) {
			if (n)
				SStream_concat0(O, ", ");
			if (!(MI->csh->syntax & CS_OPT_SYNTAX_NO_DOLLAR))
				SStream_concat1(O, '$');
			SStream_concat0(
				O, Mips_LLVM_getRegisterName(
					   MCInst_getOpVal(MI, n),
					   MI->csh->syntax &
						   CS_OPT_SYNTAX_NOREGNAME));
		}
		// Canonical MOVN/MOVZ detail retains the explicit T dependency.
		if (map_fill_detail_ops(MI))
			for (unsigned n = 0; n < 3; ++n)
				Mips_set_detail_op_reg(
					MI, n, MCInst_getOpVal(MI, n), false);
		return;
	}
	unsigned frame_id = Mips_frame_id(MI);
	if (frame_id) {
		SStream_concat0(O, frame_id == MIPS_INS_SAVE ? "save\t" :
							       "restore\t");
		for (unsigned n = 0; n < MCInst_getNumOperands(MI); ++n) {
			if (n)
				SStream_concat0(O, ", ");
			MCOperand *op = MCInst_getOperand(MI, n);
			if (MCOperand_isReg(op)) {
				if (!(MI->csh->syntax &
				      CS_OPT_SYNTAX_NO_DOLLAR))
					SStream_concat1(O, '$');
				SStream_concat0(
					O,
					Mips_LLVM_getRegisterName(
						MCOperand_getReg(op),
						MI->csh->syntax &
							CS_OPT_SYNTAX_NOREGNAME));
			} else
				printUInt64(O, MCOperand_getImm(op));
		}
		return;
	}

	Mips_LLVM_printInst(MI, MI->address, O);
#ifdef CAPSTONE_DIET
	// The regular printer omits the discarded result of these physical e2
	// forms. DIET has no alias printer; keep the public operand contract.
	if ((MI->csh->mode & CS_MODE_MIPS16) && detail_is_set(MI)) {
		switch (MCInst_getOpcode(MI)) {
		case Mips_DMT:
		case Mips_EMT:
		case Mips_DVPE:
		case Mips_EVPE:
			if (MCInst_getOpVal(MI, 0) == MIPS_REG_ZERO &&
			    !(MI->csh->detail_opt & CS_OPT_DETAIL_REAL)) {
				memset(get_detail(MI)->mips.operands, 0,
				       sizeof(get_detail(MI)->mips.operands));
				get_detail(MI)->mips.op_count = 0;
			}
			break;
		default:
			break;
		}
	}
#endif
#ifndef CAPSTONE_DIET
	MAP_SET_ALIAS_ID(MI, O, insn_alias_mnem_map,
			ARR_SIZE(insn_alias_mnem_map), alias_trie);
#endif
}

void Mips_init_cs_detail(MCInst *MI)
{
	map_set_is_alias_insn(MI, false, 0);
	MI->flat_insn->usesAliasDetails = false;
	if (detail_is_set(MI)) {
		// MIPS_OP_INVALID is zero; the complete reset includes every operand.
		memset(get_detail(MI), 0,
		       offsetof(cs_detail, mips) + sizeof(cs_mips));
	}
}

