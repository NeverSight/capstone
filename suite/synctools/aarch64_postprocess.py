"""Project AArch64 operand postprocessing requirements from LLVM descriptors."""

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
# Skipping a descriptor traversal is valid only while an unflagged traversal
# performs no writes. Review these owning helper bodies when they change.
IMPLICIT_BODY = "c29bd689018a6889866190f3ad2711a5331b4c96d0af797e45346d4c4574afd8"
WRITEBACK_BODY = "0f34dacc20441f8f80eedeb7280867aee0526c0b44fe395a1a16f587f1654f1d"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def function_body(source, marker):
    start = source.index("{", source.index(marker))
    depth, end = 1, start + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def body_digest(body):
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
    return hashlib.sha256(re.sub(r"\s+", "", body).encode()).hexdigest()


def generated_flags(source):
    text = source.read_text()
    count = int(re.search(r"MCInstrDesc Insts\[(\d+)\]", text)[1])
    op_count = int(re.search(r"MCOperandInfo OperandInfo\[(\d+)\]", text)[1])
    sections = text.split("static const AArch64InstrTable AArch64Descs = {", 1)[
        1
    ].split("\n  }, {\n")
    require(len(sections) == 3, "AArch64 descriptor layout changed")
    descriptors = re.findall(
        r"\{\s*(\d+),\s*&AArch64Descs.OperandInfo\[(\d+)\]\s*\},\s*// Inst #(\d+) = (\w+)",
        sections[0],
    )
    require(len(descriptors) == count, "Incomplete AArch64 descriptors")
    operands = [
        tuple(field.strip() for field in row.split(","))
        for row in re.findall(r"\{([^{}]+)\}", sections[1])
    ]
    require(
        len(operands) == op_count and all(len(op) == 4 for op in operands),
        "AArch64 operand layout changed",
    )
    require(
        {int(uid) for _, _, uid, _ in descriptors} == set(range(count)),
        "AArch64 opcode coverage changed",
    )
    flags = [0] * count
    for length, offset, uid, _ in descriptors:
        length, offset, uid = int(length), int(offset), int(uid)
        require(
            offset + length <= len(operands), "AArch64 operand extent exceeds table"
        )
        for reg, _, kind, constraints in operands[offset : offset + length]:
            if kind == "AARCH64_OP_IMPLICIT_IMM_0" or (
                kind == "MCOI_OPERAND_REGISTER"
                and reg
                in {
                    "AArch64_MPRRegClassID",
                    "AArch64_MPR8RegClassID",
                    "AArch64_ZTRRegClassID",
                }
            ):
                flags[uid] |= 1
            if re.fullmatch(r"CONSTRAINT_MCOI_TIED_TO\(\d+\)", constraints):
                flags[uid] |= 2
            else:
                require(
                    constraints in {"0", "CONSTRAINT_MCOI_EARLY_CLOBBER"},
                    "Unknown AArch64 operand constraint: " + constraints,
                )
    lines = [
        "/* Capstone Disassembly Engine */",
        "/* SPDX-License-Identifier: BSD-3-Clause */",
        "/* Generated by suite/synctools/aarch64_postprocess.py; do not edit. */",
        "",
        "/* Source SHA256: " + hashlib.sha256(text.encode()).hexdigest() + " */",
        "enum { AARCH64_POSTPROCESS_IMPLICIT = 1, AARCH64_POSTPROCESS_TIED = 2 };",
        "static const uint8_t AArch64PostprocessFlags[] = {",
    ]
    for index in range(0, count, 32):
        lines.append("\t" + ", ".join(map(str, flags[index : index + 32])) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def integrated_source(source):
    # Reapply the two local guards after translating a new LLVM source. Their
    # bodies and the original writeback helper remain the semantic authority.
    require(
        body_digest(
            function_body(source, "for (unsigned j = 0; j < Desc.NumOperands; j++)")
        )
        == IMPLICIT_BODY,
        "Review changed AArch64 implicit operand handling",
    )
    writeback = (ROOT / "MCInst.c").read_text()
    require(
        body_digest(function_body(writeback, "void MCInst_handleWriteback("))
        == WRITEBACK_BODY,
        "Review changed operand writeback handling",
    )
    include = '#include "AArch64GenPostprocess.inc"'
    if include not in source:
        anchor = '#include "AArch64GenDirectDecoder.inc"'
        require(source.count(anchor) == 1, "Missing AArch64 direct decoder include")
        source = source.replace(anchor, anchor + "\n" + include)
    if "AARCH64_POSTPROCESS_IMPLICIT" not in source:
        start = source.index("\t\t// Table is indexed backwards")
        end = source.index("\n\t\tif (MCInst_getOpcode(MI) == AArch64_LDR_ZA", start)
        block = source[start:end]
        source = (
            source[:start]
            + "\t\tif (AArch64PostprocessFlags[MCInst_getOpcode(MI)] &\n\t\t    AARCH64_POSTPROCESS_IMPLICIT) {\n"
            + "".join(
                "\t" + line + "\n" if line else "\n" for line in block.splitlines()
            )
            + "\t\t}\n"
            + source[end:]
        )
    if "AARCH64_POSTPROCESS_TIED" not in source:
        call = "\tMCInst_handleWriteback(MI, AArch64Descs.Insts,\n\t\t\t       ARR_SIZE(AArch64Descs.Insts));"
        require(source.count(call) == 1, "AArch64 writeback call changed")
        source = source.replace(
            call,
            "\tif (AArch64PostprocessFlags[MCInst_getOpcode(MI)] &\n\t    AARCH64_POSTPROCESS_TIED)\n\t"
            + call.replace("\n", "\n\t"),
        )
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated flags and translated-source integration",
    )
    args = parser.parse_args()
    arch = ROOT / "arch" / "AArch64"
    decoder = arch / "AArch64Disassembler.c"
    outputs = {
        arch
        / "AArch64GenPostprocess.inc": generated_flags(
            arch / "AArch64GenInstrInfo.inc"
        ),
        decoder: integrated_source(decoder.read_text()),
    }
    for path, expected in outputs.items():
        if args.check:
            require(
                path.exists() and path.read_text() == expected,
                "Regenerate " + str(path.relative_to(ROOT)),
            )
        elif not path.exists() or path.read_text() != expected:
            path.write_text(expected)


if __name__ == "__main__":
    main()
