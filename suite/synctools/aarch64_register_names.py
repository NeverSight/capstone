"""Project short AArch64 register spellings from the generated default name pool."""

import argparse
import ast
import json
import re
from pathlib import Path

ARCH = Path(__file__).resolve().parents[2] / "arch" / "AArch64"
PRINT_REG = "void printRegName(SStream *OS, unsigned Reg)\n{\n"
SHORT_REG = """#if (defined(CAPSTONE_AARCH64_SHORT_REGISTER_NAMES) || \\
     defined(CAPSTONE_AARCH64_FOUR_OUTPUT)) && !defined(CAPSTONE_DIET) && \\
	defined(CAPSTONE_USE_SYS_DYN_MEM) && !defined(CAPSTONE_HAS_OSXKERNEL) && \\
	!defined(_KERNEL_MODE) && !defined(_WIN32_WCE)
#include "AArch64GenShortRegisterNames.inc"
	if (Reg && Reg <= ARR_SIZE(short_names) && short_names[Reg - 1].length &&
	    cs_vsnprintf == cs_default_vsnprintf && !getUseMarkup() &&
	    OS->index < SSTREAM_BUF_LEN - 1) {
		SStream_concat0_small(OS, short_names[Reg - 1].text,
				      short_names[Reg - 1].length);
		return;
	}
#endif
"""
REGISTER_BODY = """	SStream_concat2(OS, markup("<reg:"),
			getRegisterName(Reg, AArch64_NoRegAltName));
	SStream_concat0(OS, markup(">"));
}"""



def generate(writer):
    strings = re.search(
        r"static const char AsmStrsNoRegAltName\[\] = \{(.*?)\};", writer, re.S
    )
    offsets = re.search(
        r"static const uint16_t RegAsmOffsetNoRegAltName\[\] = \{([\s\d,]+)\};", writer
    )
    if not strings or not offsets:
        raise ValueError("Missing the default AArch64 register tables")
    body = re.sub(r"/\*.*?\*/", "", strings[1], flags=re.S)
    literal = r'"(?:[^"\\]|\\.)*"'
    if not re.fullmatch(r"\s*(?:" + literal + r"\s*)+", body):
        raise ValueError("Unexpected register pool literal")
    pool = b"".join(ast.literal_eval("b" + token) for token in re.findall(literal, body))
    names = []
    for token in filter(None, (s.strip() for s in offsets[1].split(","))):
        start = int(token)
        name = pool[start : pool.index(0, start)].decode("ascii")
        names.append(name if 0 < len(name) <= 6 else "")
    header = [
        "/* Capstone Disassembly Engine. SPDX-License-Identifier: BSD-3-Clause */",
        "/* Generated by suite/synctools/aarch64_register_names.py. */",
        "static const struct {",
        "\tchar text[7];",
        "\tuint8_t length;",
        "} short_names[] = {",
    ]
    # Compound register names use the canonical writer. Omit a trailing run of
    # empty entries, which the caller already handles with its bounds check.
    while names and not names[-1]:
        names.pop()
    if not names:
        raise ValueError("No short AArch64 registers")
    entries = [f"{{ {json.dumps(name)}, {len(name)} }}" for name in names]
    rows = [
        "\t" + ", ".join(entries[i : i + 4]) + "," for i in range(0, len(entries), 4)
    ]
    return "\n".join([*header, *rows, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    printer = ARCH / "AArch64InstPrinter.c"
    source = printer.read_text()
    # Restore the hook after auto-sync replaces the translated printer.
    source = source.replace(PRINT_REG + SHORT_REG, PRINT_REG)
    if source.count(PRINT_REG + REGISTER_BODY) != 1:
        raise ValueError("The default register printer has changed")
    writer = (ARCH / "AArch64GenAsmWriter.inc").read_text()
    outputs = {
        ARCH / "AArch64GenShortRegisterNames.inc": generate(writer),
        printer: source.replace(PRINT_REG, PRINT_REG + SHORT_REG),
    }
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                raise SystemExit(f"Regenerate {path.name}")
            path.write_text(text)


if __name__ == "__main__":
    main()
