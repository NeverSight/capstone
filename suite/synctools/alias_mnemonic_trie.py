"""Build a double-array trie from each backend's printed alias name map."""

import argparse
from collections import deque
from pathlib import Path
import re


def generate(directory):
    arch = "PPC" if directory.name == "PowerPC" else directory.name
    source = (directory / f"{arch}Mapping.c").read_text()
    declaration = "static const name_map insn_alias_mnem_map[] = {"
    body = source.split(declaration, 1)[1].split("};", 1)[0]
    include = f"{arch}GenCSAliasMnemMap.inc"
    body = body.replace(f'#include "{include}"', (directory / include).read_text())
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S)
    row = re.compile(
        r'\s*\{\s*'
        + arch.upper()
        + r'_INS_ALIAS_(\w+)\s*,\s*(NULL|"[^"\\]*")\s*\},?'
    )
    names = []
    cursor = 0
    while body[cursor:].strip():
        match = row.match(body, cursor)
        if not match:
            raise ValueError(f"Unexpected {arch} alias name-map initializer")
        cursor = match.end()
        if match[2] == "NULL":
            if match[1] != "END" or body[cursor:].strip():
                raise ValueError(f"Unexpected {arch} alias terminator")
            break
        names.append((match[2][1:-1].encode("ascii"), match[1]))
    else:
        raise ValueError(f"Missing {arch} alias terminator")
    # Slot zero is unused. A child is at parent.offset + its byte, and
    # child.parent distinguishes overlapping sparse transition rows.
    tree = {}
    for name, enum in names:
        node = tree
        for byte in name:
            node = node.setdefault(byte, {})
        node.setdefault(None, arch.upper() + "_INS_ALIAS_" + enum)

    slots = {1: [0, 0, tree.get(None, 0)]}
    queue = deque([(1, tree)])
    while queue:
        parent, node = queue.popleft()
        children = sorted(key for key in node if key is not None)
        if not children:
            continue
        offset = 0
        while any(offset + key in slots for key in children):
            offset += 1
        slots[parent][0] = offset
        for key in children:
            slot = offset + key
            slots[slot] = [0, parent, node[key].get(None, 0)]
            queue.append((slot, node[key]))
    if max(slots) >= 65536:
        raise ValueError(f"{arch} alias trie exceeds 16-bit slot indices")
    lines = ["/* Generated by suite/synctools/alias_mnemonic_trie.py. */"]
    for slot in range(max(slots) + 1):
        offset, parent, enum = slots.get(slot, (0, 0, 0))
        lines.append(f"\t{{ {offset}, {parent}, {enum} }},")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "arch"
    for arch in ("AArch64", "Mips", "PowerPC", "Sparc"):
        directory = root / arch
        prefix = "PPC" if arch == "PowerPC" else arch
        target = directory / f"{prefix}GenAliasTrie.inc"
        content = generate(directory)
        if args.check:
            if target.read_text() != content:
                raise SystemExit(f"Regenerate {target.name}")
        else:
            target.write_text(content)
