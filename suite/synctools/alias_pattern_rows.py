"""Index generated alias patterns by their instruction opcode."""

import argparse
import re
from pathlib import Path


def entries(directory):
    arch = "PPC" if directory.name == "PowerPC" else directory.name
    writer = (directory / f"{arch}GenAsmWriter.inc").read_text()
    info = (directory / f"{arch}GenInstrInfo.inc").read_text()
    body, = re.findall(
        r"static const PatternsForOpcode OpToPatterns\[\] = \{([^;]*)\};", writer
    )
    entry = re.compile(r"\{\s*(\w+)\s*,\s*\d+\s*,\s*\d+\s*\}\s*,")
    if not re.fullmatch(r"\s*\{\s*0\s*\}\s*,?\s*", entry.sub("", body)):
        raise ValueError(f"Unrecognized {arch} alias table")
    values = dict(re.findall(r"\b(" + arch + r"_\w+)\s*=\s*(\d+)\s*,", info))
    opcodes = [int(values[name]) for name in entry.findall(body)]
    if not opcodes or sorted(set(opcodes)) != opcodes:
        raise ValueError(f"Expected distinct sorted opcodes in {arch} alias table")
    return opcodes


def generate(directory):
    opcodes = entries(directory)
    arch = "PPC" if directory.name == "PowerPC" else directory.name
    first = opcodes[0]
    if len(opcodes) > 65535:
        raise ValueError("Alias row index exceeds uint16_t")
    # Each entry records the table row of its first opcode and which of the
    # next sixteen instruction IDs have a pattern.
    masks = [0] * ((opcodes[-1] - first) // 16 + 1)
    for opcode in opcodes:
        block, bit = divmod(opcode - first, 16)
        masks[block] |= 1 << bit

    lines = [
        "/* Generated by suite/synctools/alias_pattern_rows.py. */",
        f"#define {arch}_FIRST_ALIAS_OPCODE {first}u",
        f"static const AliasOpcodeBlock {arch}_alias_blocks[] ALIAS_PATTERN_DATA = {{",
    ]
    row = 0
    for mask in masks:
        lines.append(f"\t{{ {row}, 0x{mask:04x} }},")
        row += bin(mask).count("1")
    lines += ["};", ""]
    return "\n".join(lines)


def expanded_riscv_aliases(directory):
    """Identify input opcodes that can both expand and print their own alias."""
    generated = (directory / "RISCVGenCompressedInstructionsInfo.inc").read_text()
    generated = re.sub(r"/\*.*?\*/|//[^\n]*", "", generated, flags=re.S)
    match = re.search(
        r"static bool uncompressInst\([^)]*\)\s*\{\s*"
        r"switch\s*\(\s*MCInst_getOpcode\(MI\)\s*\)\s*\{\s*"
        r"default:\s*return false;\s*(.*?)\}\s*return false;\s*\}\s*#endif",
        generated, flags=re.S,
    )
    if match is None or match[1].count("switch") or match[1].count("default"):
        raise ValueError("Unrecognized RISC-V expansion switch")
    source = match[1]
    labels = re.findall(r"\bcase\s+(RISCV_\w+)\s*:", source)
    if not labels or len(labels) != len(re.findall(r"\bcase\b", source)):
        raise ValueError("Unrecognized RISC-V expansion case")
    enum = (directory / "RISCVGenInstrInfo.inc").read_text()
    values = dict(re.findall(r"\b(RISCV_\w+)\s*=\s*(\d+)\s*,", enum))
    aliases = set(entries(directory))
    shared = sorted(name for name in labels if int(values[name]) in aliases)
    lines = ["/* Generated by suite/synctools/alias_pattern_rows.py. */",
             "static inline bool expandedOpcodeHasOwnAlias(unsigned opcode)", "{"]
    if shared:
        lines += ["\tswitch (opcode) {", *[f"\tcase {name}:" for name in shared],
                  "\t\treturn true;", "\tdefault:", "\t\treturn false;", "\t}"]
    else:
        lines += ["\t(void)opcode;", "\treturn false;"]
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "arch"
    outputs = {}
    for arch in ("AArch64", "Mips", "ARM", "PowerPC", "RISCV", "Sparc", "LoongArch"):
        name = "PPC" if arch == "PowerPC" else arch
        path = root / arch / f"{name}GenAliasPatternRows.inc"
        outputs[path] = generate(path.parent)
    riscv = root / "RISCV"
    outputs[riscv / "RISCVGenExpandedAlias.inc"] = expanded_riscv_aliases(riscv)
    for path, data in outputs.items():
        if args.check:
            if not path.is_file() or data != path.read_text():
                raise SystemExit(f"Stale {path}; rerun {Path(__file__).name}")
        else:
            path.write_text(data)


if __name__ == "__main__":
    main()
