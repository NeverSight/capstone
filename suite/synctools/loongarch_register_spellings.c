/* Link with a full LoongArch static build. The original LLVM alias lookup
 * resolves both suffix-shared strings and registers with no alternate name. */
#include <ctype.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define GET_REGINFO_ENUM
#include "../../arch/LoongArch/LoongArchGenRegisterInfo.inc"
extern const char *LoongArch_LLVM_getRegisterName(unsigned reg, unsigned alt);

int main(void)
{
	size_t longest = 0;
	for (unsigned reg = 1; reg < NUM_TARGET_REGS; ++reg) {
		const char *name = LoongArch_LLVM_getRegisterName(reg, LoongArch_RegAliasName);
		if (!name || !*name)
			return 1;
		for (const char *p = name; *p; ++p)
			if (!isalnum((unsigned char)*p) && *p != '_')
				return 1;
		const size_t length = strlen(name);
		if (length >= UINT8_MAX)
			return 1;
		if (length > longest)
			longest = length;
	}
	puts("/* Generated by suite/synctools/loongarch_register_spellings.c. */");
	printf("static const struct {\n\tuint8_t length;\n\tchar text[%zu];\n} loongarch_register_spellings[] = {\n", longest + 2);
	for (unsigned reg = 1; reg < NUM_TARGET_REGS; ++reg) {
		const char *name = LoongArch_LLVM_getRegisterName(reg, LoongArch_RegAliasName);
		printf("\t{ %zu, \"$%s\" },\n", strlen(name) + 1, name);
	}
	puts("};");
	return 0;
}
