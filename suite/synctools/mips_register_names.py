"""Generate short MIPS register names and preserve their printer hook."""

import argparse
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ARCH = ROOT / "arch" / "Mips"
ATTRIBUTE = r"""/* Use the numeric and ABI register tables in the dedicated Linux arm64 printer. */
#if defined(__linux__) && defined(__aarch64__) && defined(__clang__) && \
    defined(CAPSTONE_MIPS_ONLY)
#define MIPS_REGISTER_NAME_BANKS
#endif
#if ((defined(__linux__) && defined(__x86_64__) && defined(__GNUC__)) || \
     defined(MIPS_REGISTER_NAME_BANKS)) && \
    !defined(CAPSTONE_DIET) && defined(CAPSTONE_USE_SYS_DYN_MEM) && \
    !defined(CAPSTONE_HAS_OSXKERNEL) && !defined(_KERNEL_MODE) && \
    !defined(_WIN32_WCE)
#define MIPS_SHORT_REGISTER_NAMES
__attribute__((noinline))
#endif
"""
START = """static void printRegName(MCInst *MI, SStream *OS, MCRegister Reg)
{
\tint syntax_opt = MI->csh->syntax;
"""
HOOK = """#ifdef MIPS_SHORT_REGISTER_NAMES
#ifdef MIPS_REGISTER_NAME_BANKS
#include "MipsGenRegisterNameBanks.inc"
	if (Reg && Reg <= ARR_SIZE(mips_short_name_indices[0])) {
		const unsigned numeric = !!(syntax_opt & CS_OPT_SYNTAX_NOREGNAME);
		const unsigned index = mips_short_name_indices[numeric][Reg - 1];
#else
#include "MipsGenShortRegisterNames.inc"
	if (!(syntax_opt & CS_OPT_SYNTAX_NOREGNAME) && Reg &&
	    Reg <= ARR_SIZE(mips_short_name_indices)) {
		const unsigned index = mips_short_name_indices[Reg - 1];
#endif
		const unsigned length = mips_short_names[index].length;
		if (length && cs_vsnprintf == cs_default_vsnprintf &&
		    !OS->markup_stream && !OS->prefixed_by_markup &&
		    OS->index < SSTREAM_BUF_LEN - length) {
			const unsigned skip =
				!!(syntax_opt & CS_OPT_SYNTAX_NO_DOLLAR);
			SStream_concat0_small(
				OS, mips_short_names[index].text + skip,
				length - skip);
			return;
		}
	}
#endif
"""
BODY = """\tif (!(syntax_opt & CS_OPT_SYNTAX_NO_DOLLAR)) {
\t\tSStream_concat1(OS, '$');
\t}
\tSStream_concat0(OS, Mips_LLVM_getRegisterName(
\t\t\t\t    Reg, syntax_opt & CS_OPT_SYNTAX_NOREGNAME));
}"""


def generate(writer, printer, registers, include_numeric=False):
    writer = writer[writer.index("static const char *getRegisterName(") :]
    strings = re.search(r"static const char AsmStrs\[\] = \{(.*?)\};", writer, re.S)
    offsets = re.search(
        r"static const uint16_t RegAsmOffset\[\] = \{([\s\d,]+)\};", writer
    )
    if not strings or not offsets:
        raise ValueError("Missing MIPS register name tables")
    body = re.sub(r"/\*.*?\*/", "", strings[1], flags=re.S)
    literal = r'"(?:[^"\\]|\\.)*"'
    if not re.fullmatch(r"\s*(?:" + literal + r"\s*)+", body):
        raise ValueError("Unexpected MIPS name pool")
    pool = b"".join(
        ast.literal_eval("b" + token) for token in re.findall(literal, body)
    )
    names = []
    for token in filter(None, (x.strip() for x in offsets[1].split(","))):
        start = int(token)
        names.append(pool[start : pool.index(0, start)].decode("ascii"))
    enums = {
        name: int(value)
        for name, value in re.findall(r"\b(MIPS_REG_\w+)\s*=\s*(\d+)\s*,", registers)
    }
    if set(enums.values()) != set(range(len(names) + 1)):
        raise ValueError("MIPS public registers differ from generated writer")
    aliases = names.copy()
    owner = printer[
        printer.index(
            "const char *Mips_LLVM_getRegisterName(unsigned RegNo, bool noRegName)\n{"
        ) :
    ]
    matches = re.findall(r'((?:\s*case MIPS_REG_\w+:)+)\s*return "(\w+)";', owner)
    if not matches:
        raise ValueError("Missing MIPS ABI name aliases")
    for cases, name in matches:
        for symbol in re.findall(r"case (MIPS_REG_\w+):", cases):
            aliases[enums[symbol] - 1] = name
    unique = []
    banks = []
    for spellings in ((aliases, names) if include_numeric else (aliases,)):
        indices = []
        for name in spellings:
            text = "$" + name if name and len(name) <= 5 else ""
            if text not in unique:
                unique.append(text)
            indices.append(unique.index(text))
        banks.append(indices)
    if len(unique) > 256:
        raise ValueError("Too many short MIPS names for a byte index")
    dimensions = f"[2][{len(names)}]" if include_numeric else "[]"
    out = [
        "/* Capstone Disassembly Engine. SPDX-License-Identifier: BSD-3-Clause */",
        "/* Generated by suite/synctools/mips_register_names.py. */",
        f"static const uint8_t mips_short_name_indices{dimensions} = {{",
    ]
    for indices in banks:
        indent = "\t\t" if include_numeric else "\t"
        if include_numeric:
            out.append("\t{")
        out.extend(
            indent + ", ".join(map(str, indices[n : n + 16])) + ","
            for n in range(0, len(indices), 16)
        )
        if include_numeric:
            out.append("\t},")
    out.extend(
        [
            "};",
            "static const struct {",
            "\tchar text[7];",
            "\tuint8_t length;",
            "} mips_short_names[] = {",
        ]
    )
    rows = ["{ " + json.dumps(text) + ", " + str(len(text)) + " }" for text in unique]
    out.extend("\t" + ", ".join(rows[n : n + 4]) + "," for n in range(0, len(rows), 4))
    return "\n".join([*out, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    printer = ARCH / "MipsInstPrinter.c"
    source = printer.read_text().replace(ATTRIBUTE + START + HOOK, START)
    if source.count(START + BODY) != 1:
        raise ValueError("The MIPS register printer has changed")
    writer = (ARCH / "MipsGenAsmWriter.inc").read_text()
    registers = (ROOT / "include/capstone/mips.h").read_text()
    outputs = {
        ARCH / "MipsGenShortRegisterNames.inc": generate(writer, source, registers),
        ARCH / "MipsGenRegisterNameBanks.inc": generate(writer, source, registers, True),
        printer: source.replace(START, ATTRIBUTE + START + HOOK),
    }
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                raise SystemExit("Regenerate " + path.name)
            path.write_text(text)


if __name__ == "__main__":
    main()
