"""Generate short MIPS register names and preserve their printer hook."""

import argparse
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ARCH = ROOT / "arch" / "Mips"
ATTRIBUTE = "#if defined(__linux__) && defined(__x86_64__) && defined(__GNUC__) && \\\n    !defined(CAPSTONE_DIET) && defined(CAPSTONE_USE_SYS_DYN_MEM) && \\\n    !defined(CAPSTONE_HAS_OSXKERNEL) && !defined(_KERNEL_MODE) && \\\n    !defined(_WIN32_WCE)\n#define MIPS_SHORT_REGISTER_NAMES\n__attribute__((noinline))\n#endif\n"
START = """static void printRegName(MCInst *MI, SStream *OS, MCRegister Reg)
{
\tint syntax_opt = MI->csh->syntax;
"""
HOOK = '#ifdef MIPS_SHORT_REGISTER_NAMES\n#include "MipsGenShortRegisterNames.inc"\n\tif (!(syntax_opt & CS_OPT_SYNTAX_NOREGNAME) && Reg &&\n\t    Reg <= ARR_SIZE(mips_short_name_indices)) {\n\t\tconst unsigned index = mips_short_name_indices[Reg - 1];\n\t\tconst unsigned length = mips_short_names[index].length;\n\t\tif (length && cs_vsnprintf == cs_default_vsnprintf &&\n\t\t    !OS->markup_stream && !OS->prefixed_by_markup &&\n\t\t    OS->index < SSTREAM_BUF_LEN - length) {\n\t\t\tconst unsigned skip =\n\t\t\t\t!!(syntax_opt & CS_OPT_SYNTAX_NO_DOLLAR);\n\t\t\tSStream_concat0_small(\n\t\t\t\tOS, mips_short_names[index].text + skip,\n\t\t\t\tlength - skip);\n\t\t\treturn;\n\t\t}\n\t}\n#endif\n'
BODY = """\tif (!(syntax_opt & CS_OPT_SYNTAX_NO_DOLLAR)) {
\t\tSStream_concat1(OS, '$');
\t}
\tSStream_concat0(OS, Mips_LLVM_getRegisterName(
\t\t\t\t    Reg, syntax_opt & CS_OPT_SYNTAX_NOREGNAME));
}"""


def generate(writer, printer, registers):
    writer = writer[writer.index("static const char *getRegisterName(") :]
    strings = re.search(r"static const char AsmStrs\[\] = \{(.*?)\};", writer, re.S)
    offsets = re.search(
        r"static const uint16_t RegAsmOffset\[\] = \{([\s\d,]+)\};", writer
    )
    if not strings or not offsets:
        raise ValueError("Missing MIPS register name tables")
    body = re.sub(r"/\*.*?\*/", "", strings[1], flags=re.S)
    literal = r'"(?:[^"\\]|\\.)*"'
    if not re.fullmatch(r"\s*(?:" + literal + r"\s*)+", body):
        raise ValueError("Unexpected MIPS name pool")
    pool = b"".join(
        ast.literal_eval("b" + token) for token in re.findall(literal, body)
    )
    names = []
    for token in filter(None, (x.strip() for x in offsets[1].split(","))):
        start = int(token)
        names.append(pool[start : pool.index(0, start)].decode("ascii"))
    enums = {
        name: int(value)
        for name, value in re.findall(r"\b(MIPS_REG_\w+)\s*=\s*(\d+)\s*,", registers)
    }
    if set(enums.values()) != set(range(len(names) + 1)):
        raise ValueError("MIPS public registers differ from generated writer")
    aliases = names.copy()
    owner = printer[
        printer.index(
            "const char *Mips_LLVM_getRegisterName(unsigned RegNo, bool noRegName)\n{"
        ) :
    ]
    matches = re.findall(r'((?:\s*case MIPS_REG_\w+:)+)\s*return "(\w+)";', owner)
    if not matches:
        raise ValueError("Missing MIPS ABI name aliases")
    for cases, name in matches:
        for symbol in re.findall(r"case (MIPS_REG_\w+):", cases):
            aliases[enums[symbol] - 1] = name
    unique = []
    indices = []
    for name in aliases:
        text = "$" + name if name and len(name) <= 5 else ""
        if text not in unique:
            unique.append(text)
        indices.append(unique.index(text))
    if len(unique) > 256:
        raise ValueError("Too many short MIPS names for a byte index")
    out = [
        "/* Capstone Disassembly Engine. SPDX-License-Identifier: BSD-3-Clause */",
        "/* Generated by suite/synctools/mips_register_names.py. */",
        "static const uint8_t mips_short_name_indices[] = {",
    ]
    out.extend(
        "\t" + ", ".join(map(str, indices[n : n + 16])) + ","
        for n in range(0, len(indices), 16)
    )
    out.extend(
        [
            "};",
            "static const struct {",
            "\tchar text[7];",
            "\tuint8_t length;",
            "} mips_short_names[] = {",
        ]
    )
    rows = ["{ " + json.dumps(text) + ", " + str(len(text)) + " }" for text in unique]
    out.extend("\t" + ", ".join(rows[n : n + 4]) + "," for n in range(0, len(rows), 4))
    return "\n".join([*out, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    printer = ARCH / "MipsInstPrinter.c"
    source = printer.read_text().replace(ATTRIBUTE + START + HOOK, START)
    if source.count(START + BODY) != 1:
        raise ValueError("The MIPS register printer has changed")
    outputs = {
        ARCH
        / "MipsGenShortRegisterNames.inc": generate(
            (ARCH / "MipsGenAsmWriter.inc").read_text(),
            source,
            (ROOT / "include/capstone/mips.h").read_text(),
        ),
        printer: source.replace(START, ATTRIBUTE + START + HOOK),
    }
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                raise SystemExit("Regenerate " + path.name)
            path.write_text(text)


if __name__ == "__main__":
    main()
