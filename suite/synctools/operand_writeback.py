"""Project ARM and RISC-V writeback requirements from LLVM descriptors."""

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
# An unflagged traversal must perform no writes. Review the owning helper when
# its implementation changes; flagged instructions still use that helper.
WRITEBACK_BODY = "0f34dacc20441f8f80eedeb7280867aee0526c0b44fe395a1a16f587f1654f1d"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def function_body(source, marker):
    start = source.index("{", source.index(marker))
    depth, end = 1, start + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def body_digest(body):
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
    return hashlib.sha256(re.sub(r"\s+", "", body).encode()).hexdigest()


def generated_flags(arch, source):
    text = source.read_text()
    count = int(re.search(r"MCInstrDesc Insts\[(\d+)\]", text)[1])
    op_count = int(re.search(r"MCOperandInfo OperandInfo\[(\d+)\]", text)[1])
    sections = text.split(f"static const {arch}InstrTable {arch}Descs = {{", 1)[
        1
    ].split("\n  }, {\n")
    require(len(sections) == 3, f"{arch} descriptor layout changed")
    descriptors = re.findall(
        r"\{\s*(\d+),\s*&"
        + arch
        + r"Descs.OperandInfo\[(\d+)\]\s*\},\s*// Inst #(\d+) = (\w+)",
        sections[0],
    )
    require(len(descriptors) == count, f"Incomplete {arch} descriptors")
    operands = [
        tuple(field.strip() for field in row.split(","))
        for row in re.findall(r"\{([^{}]+)\}", sections[1])
    ]
    require(
        len(operands) == op_count and all(len(op) == 4 for op in operands),
        f"{arch} operand layout changed",
    )
    require(
        {int(uid) for _, _, uid, _ in descriptors} == set(range(count)),
        f"{arch} opcode coverage changed",
    )
    flags = [0] * count
    for length, offset, uid, _ in descriptors:
        length, offset, uid = int(length), int(offset), int(uid)
        require(
            offset + length <= len(operands), f"{arch} operand extent exceeds table"
        )
        for _, _, _, constraints in operands[offset : offset + length]:
            if re.fullmatch(r"CONSTRAINT_MCOI_TIED_TO\(\d+\)", constraints):
                flags[uid] = 1
            else:
                require(
                    constraints in {"0", "CONSTRAINT_MCOI_EARLY_CLOBBER"},
                    f"Unknown {arch} operand constraint: " + constraints,
                )
    lines = [
        "/* Capstone Disassembly Engine */",
        "/* SPDX-License-Identifier: BSD-3-Clause */",
        "/* Generated by suite/synctools/operand_writeback.py; do not edit. */",
        "",
        "/* Source SHA256: " + hashlib.sha256(text.encode()).hexdigest() + " */",
        f"static const uint8_t {arch}WritebackFlags[] = {{",
    ]
    for index in range(0, count, 32):
        lines.append("\t" + ", ".join(map(str, flags[index : index + 32])) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def integrated_source(arch, source):
    writeback = (ROOT / "MCInst.c").read_text()
    require(
        body_digest(function_body(writeback, "void MCInst_handleWriteback("))
        == WRITEBACK_BODY,
        "Review changed operand writeback handling",
    )
    include = f'#include "{arch}GenWriteback.inc"'
    if include not in source:
        anchor = f'#include "{arch}GenDirectDecoder.inc"'
        require(source.count(anchor) == 1, f"Missing {arch} direct decoder include")
        source = source.replace(anchor, anchor + "\n" + include)
    guard = f"if ({arch}WritebackFlags[MCInst_getOpcode(MI)])"
    if guard not in source:
        calls = list(
            re.finditer(
                r"\tMCInst_handleWriteback\(MI, "
                + arch
                + r"Descs.Insts,\s*ARR_SIZE\("
                + arch
                + r"Descs.Insts\)\);",
                source,
            )
        )
        require(len(calls) == 1, f"Review changed {arch} writeback entry")
        call = calls[0]
        source = (
            source[: call.start()]
            + "\t"
            + guard
            + "\n\t"
            + call[0].replace("\n", "\n\t")
            + source[call.end() :]
        )
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check flags and translated-source integration",
    )
    args = parser.parse_args()
    for arch in ["ARM", "RISCV"]:
        directory = ROOT / "arch" / arch
        decoder = directory / f"{arch}Disassembler.c"
        outputs = {
            directory
            / f"{arch}GenWriteback.inc": generated_flags(
                arch, directory / f"{arch}GenInstrInfo.inc"
            ),
            decoder: integrated_source(arch, decoder.read_text()),
        }
        for path, expected in outputs.items():
            if args.check:
                require(
                    path.exists() and path.read_text() == expected,
                    "Regenerate " + str(path.relative_to(ROOT)),
                )
            elif not path.exists() or path.read_text() != expected:
                path.write_text(expected)


if __name__ == "__main__":
    main()
