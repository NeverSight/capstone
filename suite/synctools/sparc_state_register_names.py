"""Project SPARC V9 state register spellings with their percent prefix."""

import argparse
import ast
import json
import re
from pathlib import Path

ARCH = Path(__file__).resolve().parents[2] / "arch" / "Sparc"
PRINT_REG = (
    "static void printRegNameAlt(SStream *OS, MCRegister Reg, unsigned AltIdx)\n{\n"
)
REGISTER_BODY = """\tSStream_concat1(OS, '%');
\tSStream_concat0(OS, getRegisterName(Reg, AltIdx));
}"""
SHORT_REG = """#if defined(CAPSTONE_SPARC_SHORT_STATE_REGISTER_NAMES) && !defined(CAPSTONE_DIET) && \\
	(defined(__clang__) || defined(_MSC_VER))
#include "SparcGenShortStateRegisterNames.inc"
\tif (AltIdx == Sparc_RegNamesStateReg && Reg &&
\t    Reg <= ARR_SIZE(short_names) && short_names[Reg - 1].length &&
\t    !(OS->markup_stream && OS->prefixed_by_markup) &&
\t    OS->index < SSTREAM_BUF_LEN - short_names[Reg - 1].length) {
\t\tSStream_concat0_small(OS, short_names[Reg - 1].text,
\t\t\t\t      short_names[Reg - 1].length);
\t\treturn;
\t}
#endif
"""


def names(writer, alternate):
    strings = re.search(
        r"static const char AsmStrs" + alternate + r"\[\] = \{(.*?)\};",
        writer,
        re.S,
    )
    offsets = re.search(
        r"static const uint(?:8|16)_t RegAsmOffset"
        + alternate
        + r"\[\] = \{([\s\d,]+)\};",
        writer,
    )
    if not strings or not offsets:
        raise ValueError("Missing the SPARC register pool " + alternate)
    body = re.sub(r"/\*.*?\*/", "", strings[1], flags=re.S)
    literal = r'"(?:[^"\\]|\\.)*"'
    if not re.fullmatch(r"\s*(?:" + literal + r"\s*)+", body):
        raise ValueError("Unexpected register pool literal")
    pool = b"".join(
        ast.literal_eval("b" + token) for token in re.findall(literal, body)
    )
    result = []
    for token in filter(None, (s.strip() for s in offsets[1].split(","))):
        offset = int(token)
        result.append(pool[offset : pool.index(0, offset)].decode("ascii"))
    return result


def generate(writer):
    fallback = names(writer, "NoRegAltName")
    alternate = names(writer, "RegNamesStateReg")
    if len(fallback) != len(alternate):
        raise ValueError("The SPARC register pools have different bounds")
    state_case = writer.split("case Sparc_RegNamesStateReg:", 1)[1]
    if "return getRegisterName(RegNo, Sparc_NoRegAltName);" not in state_case:
        raise ValueError("The SPARC V9 name fallback has changed")
    resolved = [
        "%" + (name or default) if 0 < len(name or default) <= 5 else ""
        for name, default in zip(alternate, fallback)
    ]
    entries = [f"{{ {json.dumps(name)}, {len(name)} }}" for name in resolved]
    rows = [
        "\t" + ", ".join(entries[i : i + 4]) + "," for i in range(0, len(entries), 4)
    ]
    return "\n".join(
        [
            "/* Capstone Disassembly Engine. SPDX-License-Identifier: BSD-3-Clause */",
            "/* Generated by suite/synctools/sparc_state_register_names.py. */",
            "static const struct {",
            "\tchar text[7];",
            "\tuint8_t length;",
            "} short_names[] = {",
            *rows,
            "};",
            "",
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    printer = ARCH / "SparcInstPrinter.c"
    source = printer.read_text().replace(PRINT_REG + SHORT_REG, PRINT_REG)
    if source.count(PRINT_REG + REGISTER_BODY) != 1:
        raise ValueError("The SPARC alternate register printer has changed")
    outputs = {
        ARCH
        / "SparcGenShortStateRegisterNames.inc": generate(
            (ARCH / "SparcGenAsmWriter.inc").read_text()
        ),
        printer: source.replace(PRINT_REG, PRINT_REG + SHORT_REG),
    }
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                raise SystemExit(f"Regenerate {path.name}")
            path.write_text(text)


if __name__ == "__main__":
    main()
