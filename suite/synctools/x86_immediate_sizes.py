"""Index the existing x86 immediate-size metadata by each build's opcode IDs.

X86ImmSize.inc remains the semantic source. The two instruction enums assign
separate IDs in full and reduced builds. One byte holds both four-bit sizes;
zero entries preserve the old lookup's result for every absent instruction.
"""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
ROW = re.compile(r"\s*\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(X86_\w+)\s*\}\s*,")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def generate(directory):
    source = re.sub(
        r"/\*.*?\*/|//[^\n]*", "",
        (directory / "X86ImmSize.inc").read_text(), flags=re.S,
    )
    rows = []
    pos = 0
    while source[pos:].strip():
        match = ROW.match(source, pos)
        require(
            match is not None,
            f"Unexpected immediate-size row: {source[pos:pos + 80]!r}",
        )
        enc, size, name = match.groups()
        enc, size = int(enc), int(size)
        require(enc < 16 and size < 16, f"Sizes do not fit four bits: {name}")
        rows.append((enc, size, name))
        pos = match.end()
    require(rows, "Missing immediate-size rows")
    lines = [
        "/* Generated by suite/synctools/x86_immediate_sizes.py. */",
        "/* X86ImmSize.inc owns the sizes; instruction enums own the indices. */",
    ]
    for reduced in (True, False):
        suffix = "_reduce" if reduced else ""
        text = (directory / f"X86GenInstrInfo{suffix}.inc").read_text()
        entries = re.findall(r"\b(X86_\w+)\s*=\s*(\d+)", text)
        ids = {name: int(value) for name, value in entries}
        require(len(entries) == len(ids), "Duplicate instruction enum name")
        require("X86_INSTRUCTION_LIST_END" in ids, "Missing instruction enum bound")
        values = [0] * ids["X86_INSTRUCTION_LIST_END"]
        previous = -1
        for enc, size, name in rows:
            require(name in ids, f"Missing instruction: {name}")
            index = ids[name]
            require(
                previous < index < len(values),
                f"Unsorted, duplicate or out-of-range instruction: {name}",
            )
            values[index] = (enc << 4) | size
            previous = index
        lines.append("#ifdef CAPSTONE_X86_REDUCE" if reduced else "#else")
        lines.append("static const uint8_t x86_imm_sizes[] = {")
        for index in range(0, len(values), 24):
            lines.append("\t" + ", ".join(map(str, values[index:index + 24])) + ",")
        lines.append("};")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = ROOT / "arch/X86"
    output = directory / "X86GenImmSize.inc"
    expected = generate(directory)
    if args.check:
        require(
            output.read_text() == expected,
            f"Stale {output}; rerun {Path(__file__).name}",
        )
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
