"""Generate XCore detail operands embedded in the assembly writer's first fragment."""

import argparse
import ast
from pathlib import Path
import re

ARCH = Path(__file__).resolve().parents[2] / "arch" / "XCore"
INVALID = "XCORE_REG_INVALID"


def initializer(source, declaration):
    return source.split(declaration + " = {", 1)[1].split("};", 1)[0]


def operands(fragment, registers):
    # The writer supplies the rest of TSETMR's register name dynamically.
    _, _, text = fragment.partition(" ")
    text = text.rstrip(" ,")
    if not text or fragment.startswith("#") or text == "r":
        return ("REGISTERS", INVALID, INVALID, 0)

    regs = []
    for token in text.split(", "):
        if token in registers and len(regs) < 2:
            regs.append(registers[token])
            continue
        memory = re.fullmatch(r"(\w+)\[(?:(\d+)\])?", token)
        if memory and len(regs) <= 1 and text.endswith(token):
            base, displacement = memory.groups()
            if base in registers:
                base = registers[base]
            elif base in ("ps", "res", "t") and displacement is None:
                base = INVALID
            else:
                raise ValueError(f"Unknown memory base in {fragment!r}")
            kind = "OPEN_MEMORY" if displacement is None else "FIXED_MEMORY"
            return (kind, regs[0] if regs else INVALID, base, int(displacement or 0))
        raise ValueError(f"Unhandled fixed operand in {fragment!r}")
    return ("REGISTERS", *(regs + [INVALID, INVALID])[:2], 0)


def generate():
    writer = (ARCH / "XCoreGenAsmWriter.inc").read_text()
    mapping = (ARCH / "XCoreMapping.c").read_text()
    registers = {
        name: enum
        for enum, name in re.findall(r'\{\s*(XCORE_REG_\w+),\s*"(\w+)"\s*}', mapping)
    }
    asm = initializer(writer, "static const char AsmStrs[]")
    chars = ast.literal_eval("[" + re.sub(r"/\*.*?\*/", "", asm) + "]")
    strings = bytes(ord(c) if isinstance(c, str) else c for c in chars)
    op_info = initializer(writer, "static const uint32_t OpInfo[]")
    mask = int(re.search(r"AsmStrs\s*\+\s*\(Bits & (\d+)\)", writer)[1])
    plans = [operands("", registers)]
    indices = []
    for word in re.sub(r"//[^\n]*", "", op_info).strip().split(","):
        offset = int(word.strip().rstrip("U")) & mask
        fragment = (
            strings[offset - 1 : strings.index(0, offset - 1)].decode()
            if offset
            else ""
        )
        plan = operands(fragment, registers)
        if plan not in plans:
            plans.append(plan)
        indices.append(plans.index(plan))
    if len(plans) > 256 or any(not 0 <= plan[3] <= 255 for plan in plans):
        raise ValueError("Fixed operands exceed the XCore literal table format")
    lines = [
        "/* Generated by suite/synctools/xcore_literal_operands.py. */",
        "static const struct XCoreLiteralOperands xcore_literal_operands[] = {",
    ]
    for kind, first, second, displacement in plans:
        lines.append(
            f"\t{{ XCORE_LITERAL_{kind}, {first}, {second}, {displacement} }},"
        )
    lines += ["};", "", "static const uint8_t xcore_literal_index[] = {"]
    for start in range(0, len(indices), 16):
        lines.append("\t" + ", ".join(map(str, indices[start : start + 16])) + ",")
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    options = argparse.ArgumentParser(description=__doc__)
    options.add_argument(
        "--check", action="store_true", help="check the committed table"
    )
    args = options.parse_args()
    path = ARCH / "XCoreGenLiteralOperands.inc"
    contents = generate()
    if args.check:
        if path.read_text() != contents:
            raise SystemExit(f"{path.name} needs regeneration")
    else:
        path.write_text(contents)
